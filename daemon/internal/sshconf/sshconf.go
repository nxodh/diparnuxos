// Package sshconf 는 SSH 서버의 고급 설정(포트, 비밀번호 로그인), 공개 키 목록, 최근 접속 기록을 다룬다.
//
// 설정은 /etc/ssh/sshd_config.d/40-diparnux-ssh.conf 한 파일로 쓴다. sshd 는 먼저 읽은 값을 쓰므로 계정 헬퍼의
// 50-diparnux.conf 보다 앞서 읽도록 40 번을 쓴다. 쓰기 전에 sshd -t 로 검사하고, 실패하면 이전 파일로 되돌린다.
// 비밀번호 로그인을 막을 때는 등록된 공개 키가 하나도 없으면 거부한다(스스로 잠기지 않게).
package sshconf

import (
	"bufio"
	"context"
	"crypto/sha256"
	"encoding/base64"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/nxodh/diparnuxos/daemon/internal/admin"
	"github.com/nxodh/diparnuxos/daemon/internal/platform"
)

// 경로와 기본값이다.
const (
	DropinPath  = "/etc/ssh/sshd_config.d/40-diparnux-ssh.conf"
	DefaultPort = 22
	sshUnit     = "ssh.service"
)

// 오류 코드다.
const (
	CodeInvalidInput = "invalid_input"
	CodeNoKeys       = "no_keys"
	CodeSSHConfig    = "ssh_config"
	CodeNotFound     = "not_found"
	CodeInternal     = "internal"
)

// Error 는 코드를 가진 오류다.
type Error struct{ Code, Message string }

func (e *Error) Error() string { return e.Code + ": " + e.Message }

func errf(code, f string, a ...any) *Error { return &Error{code, fmt.Sprintf(f, a...)} }

// Settings 는 이 패키지가 관리하는 SSH 설정이다.
type Settings struct {
	Port int `json:"port"`
	// PasswordLogin 은 nil 이면 정하지 않은 것이다(이미지 기본 정책을 따른다).
	PasswordLogin *bool `json:"password_login"`
}

// Render 는 설정 파일을 만든다. 비어 있으면 빈 문자열이다(파일을 지운다).
func Render(s Settings) string {
	if (s.Port == 0 || s.Port == DefaultPort) && s.PasswordLogin == nil {
		return ""
	}
	var b strings.Builder
	b.WriteString("# Generated by diparnuxd. Change it with 'diparnux ssh'; manual edits are overwritten.\n")
	if s.Port != 0 && s.Port != DefaultPort {
		fmt.Fprintf(&b, "Port %d\n", s.Port)
	}
	if s.PasswordLogin != nil {
		if *s.PasswordLogin {
			b.WriteString("PasswordAuthentication yes\n")
		} else {
			b.WriteString("PasswordAuthentication no\nKbdInteractiveAuthentication no\n")
		}
	}
	return b.String()
}

// Parse 는 Render 가 만든 파일을 읽는다.
func Parse(text string) Settings {
	s := Settings{Port: DefaultPort}
	for _, line := range strings.Split(text, "\n") {
		f := strings.Fields(line)
		if len(f) != 2 || strings.HasPrefix(f[0], "#") {
			continue
		}
		switch f[0] {
		case "Port":
			if n, err := strconv.Atoi(f[1]); err == nil && n >= 1 && n <= 65535 {
				s.Port = n
			}
		case "PasswordAuthentication":
			v := f[1] == "yes"
			s.PasswordLogin = &v
		}
	}
	return s
}

// ---- 공개 키 ----

// Key 는 authorized_keys 의 한 줄이다.
type Key struct {
	Type        string `json:"type"`
	Fingerprint string `json:"fingerprint"`
	Comment     string `json:"comment"`
}

var keyTypes = map[string]bool{
	"ssh-ed25519": true, "ssh-rsa": true, "ecdsa-sha2-nistp256": true, "ecdsa-sha2-nistp384": true,
	"ecdsa-sha2-nistp521": true, "sk-ssh-ed25519@openssh.com": true, "sk-ecdsa-sha2-nistp256@openssh.com": true,
}

// ParseKeyLine 은 옵션이 없는 공개 키 한 줄을 검사하고 지문을 계산한다.
func ParseKeyLine(line string) (Key, error) {
	line = strings.TrimSpace(line)
	if line == "" || strings.ContainsAny(line, "\n\r\x00") || len(line) > 8192 {
		return Key{}, errors.New("the key must be a single line")
	}
	f := strings.Fields(line)
	if len(f) < 2 {
		return Key{}, errors.New("the key needs a type and a base64 body, such as: ssh-ed25519 AAAA... name")
	}
	if !keyTypes[f[0]] {
		return Key{}, fmt.Errorf("the key type %q is not supported (use ssh-ed25519, ssh-rsa or an ecdsa type)", f[0])
	}
	blob, err := base64.StdEncoding.DecodeString(f[1])
	if err != nil || len(blob) < 8 {
		return Key{}, errors.New("the key body is not valid base64")
	}
	// 본문은 길이 접두사 문자열(키 종류)로 시작한다. 선언한 종류와 같아야 한다.
	n := int(blob[0])<<24 | int(blob[1])<<16 | int(blob[2])<<8 | int(blob[3])
	if n < 1 || 4+n > len(blob) || string(blob[4:4+n]) != f[0] {
		return Key{}, errors.New("the key body does not match its type")
	}
	sum := sha256.Sum256(blob)
	comment := ""
	if len(f) > 2 {
		comment = strings.Join(f[2:], " ")
	}
	return Key{Type: f[0], Fingerprint: "SHA256:" + base64.RawStdEncoding.EncodeToString(sum[:]), Comment: comment}, nil
}

// ParseKeys 는 authorized_keys 내용에서 알아본 키를 목록으로 만든다. 주석, 빈 줄, 옵션이 붙은 줄은 건너뛴다.
func ParseKeys(data []byte) []Key {
	var out []Key
	sc := bufio.NewScanner(strings.NewReader(string(data)))
	sc.Buffer(make([]byte, 0, 64<<10), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if k, err := ParseKeyLine(line); err == nil {
			out = append(out, k)
		}
	}
	return out
}

// AddKey 는 키를 authorized_keys 내용에 더한다. 같은 지문이 있으면 그대로 둔다.
func AddKey(data []byte, line string) ([]byte, Key, bool, error) {
	k, err := ParseKeyLine(line)
	if err != nil {
		return data, k, false, err
	}
	for _, e := range ParseKeys(data) {
		if e.Fingerprint == k.Fingerprint {
			return data, k, false, nil
		}
	}
	out := strings.TrimRight(string(data), "\n")
	if out != "" {
		out += "\n"
	}
	return []byte(out + strings.TrimSpace(line) + "\n"), k, true, nil
}

// RemoveKey 는 지문이 같은 줄을 지운다. 나머지 줄(주석 포함)은 그대로 둔다.
func RemoveKey(data []byte, fingerprint string) ([]byte, bool) {
	var kept []string
	removed := false
	for _, line := range strings.Split(strings.TrimRight(string(data), "\n"), "\n") {
		t := strings.TrimSpace(line)
		if t != "" && !strings.HasPrefix(t, "#") {
			if k, err := ParseKeyLine(t); err == nil && k.Fingerprint == fingerprint {
				removed = true
				continue
			}
		}
		kept = append(kept, line)
	}
	out := strings.Join(kept, "\n")
	if out != "" {
		out += "\n"
	}
	return []byte(out), removed
}

// ---- 접속 기록 ----

// LoginEvent 는 sshd 의 인증 결과 한 줄이다.
type LoginEvent struct {
	Time   string `json:"time"`
	Result string `json:"result"` // accepted, failed
	User   string `json:"user"`
	Method string `json:"method"`
	From   string `json:"from"`
}

var (
	acceptedRE = regexp.MustCompile(`Accepted (\S+) for (\S+) from (\S+) port \d+`)
	failedRE   = regexp.MustCompile(`Failed (\S+) for (?:invalid user )?(\S+) from (\S+) port \d+`)
	invalidRE  = regexp.MustCompile(`Invalid user (\S+) from (\S+)`)
)

// ParseAuthLog 는 `journalctl -u ssh -o short-iso` 출력에서 접속 결과를 읽는다. 새것이 먼저다.
func ParseAuthLog(text string, limit int) []LoginEvent {
	var out []LoginEvent
	lines := strings.Split(text, "\n")
	for i := len(lines) - 1; i >= 0; i-- {
		line := lines[i]
		ts := ""
		if sp := strings.IndexByte(line, ' '); sp > 0 {
			ts = line[:sp]
		}
		var ev *LoginEvent
		if m := acceptedRE.FindStringSubmatch(line); m != nil {
			ev = &LoginEvent{Result: "accepted", Method: m[1], User: m[2], From: m[3]}
		} else if m := failedRE.FindStringSubmatch(line); m != nil {
			ev = &LoginEvent{Result: "failed", Method: m[1], User: m[2], From: m[3]}
		} else if m := invalidRE.FindStringSubmatch(line); m != nil {
			ev = &LoginEvent{Result: "failed", Method: "unknown", User: m[1], From: m[2]}
		}
		if ev == nil {
			continue
		}
		ev.Time = ts
		out = append(out, *ev)
		if limit > 0 && len(out) >= limit {
			break
		}
	}
	return out
}

// ---- 관리자 ----

// KeyStore 는 사용자 authorized_keys 의 읽기와 쓰기다. *admin.Client 가 만족한다.
type KeyStore interface {
	ReadAuthorizedKeys(ctx context.Context, user string) ([]byte, error)
	WriteAuthorizedKeys(ctx context.Context, user string, data []byte) error
}

// FileWriter 는 sshd 설정 파일을 쓴다. *admin.Client 가 만족한다.
type FileWriter interface {
	Write(ctx context.Context, path string, data []byte, secret bool) error
	Remove(ctx context.Context, path string) error
}

// Manager 는 SSH 설정을 읽고 바꾼다.
type Manager struct {
	Files  FileWriter
	Keys   KeyStore
	Runner platform.Runner
	// Users 는 키를 관리할 수 있는 계정 이름을 돌려준다(로그인 계정). nil 이면 키 관리는 Users 검사를 하지 않는다.
	Users func() []string
	// Dropin 은 설정 파일 경로다(시험용). 비어 있으면 DropinPath 다.
	Dropin string
	// ConfigPath 는 읽을 파일 경로다(시험이 /etc 대신 임시 경로를 줄 때). 비어 있으면 Dropin 이다.
	ConfigPath string
	// HostKeyDir 는 호스트 키 디렉터리다. 비어 있으면 /etc/ssh 다.
	HostKeyDir string
}

func (m *Manager) dropin() string {
	if m.Dropin != "" {
		return m.Dropin
	}
	return DropinPath
}

func (m *Manager) readPath() string {
	if m.ConfigPath != "" {
		return m.ConfigPath
	}
	return m.dropin()
}

// Settings 는 지금 적용된 설정이다.
func (m *Manager) Settings() Settings {
	data, err := os.ReadFile(m.readPath())
	if err != nil {
		return Settings{Port: DefaultPort}
	}
	return Parse(string(data))
}

// CountKeys 는 모든 로그인 계정에 등록된 공개 키의 수다.
func (m *Manager) CountKeys(ctx context.Context) (int, error) {
	if m.Users == nil || m.Keys == nil {
		return 0, nil
	}
	total := 0
	for _, u := range m.Users() {
		data, err := m.Keys.ReadAuthorizedKeys(ctx, u)
		if err != nil {
			continue
		}
		total += len(ParseKeys(data))
	}
	return total, nil
}

// Apply 는 새 설정을 쓰고 sshd 가 받아들이는지 확인한다. 실패하면 이전 파일로 되돌린다.
// sshActive 가 true 이면 sshd 를 다시 읽게 한다. 연결 중인 세션은 끊기지 않는다.
func (m *Manager) Apply(ctx context.Context, s Settings, sshActive bool) error {
	if s.Port != 0 && (s.Port < 1 || s.Port > 65535) {
		return errf(CodeInvalidInput, "the SSH port must be 1-65535")
	}
	if s.PasswordLogin != nil && !*s.PasswordLogin {
		n, err := m.CountKeys(ctx)
		if err != nil {
			return errf(CodeInternal, "counting the public keys: %v", err)
		}
		if n == 0 {
			return errf(CodeNoKeys, "add a public key to an account first; turning password login off without a key would lock you out")
		}
	}
	prev, rerr := os.ReadFile(m.readPath())
	text := Render(s)
	var werr error
	if text == "" {
		werr = m.Files.Remove(ctx, m.dropin())
	} else {
		werr = m.Files.Write(ctx, m.dropin(), []byte(text), false)
	}
	if werr != nil {
		return errf(CodeSSHConfig, "writing the SSH configuration: %v", werr)
	}
	if err := m.check(ctx); err != nil {
		if rerr == nil {
			_ = m.Files.Write(ctx, m.dropin(), prev, false)
		} else {
			_ = m.Files.Remove(ctx, m.dropin())
		}
		return errf(CodeSSHConfig, "sshd rejected the configuration (it was reverted): %v", err)
	}
	if sshActive {
		res, err := m.Runner.Run(ctx, platform.Command{Name: "systemctl", Args: []string{"reload", sshUnit}, Timeout: 20 * time.Second, MaxOutput: 8 << 10})
		if err != nil || res.ExitCode != 0 {
			return errf(CodeSSHConfig, "the new SSH configuration is saved but sshd could not reload it")
		}
	}
	return nil
}

// check 는 sshd -t 로 설정을 검사한다. sshd 가 없으면(이미지에 없음) 검사하지 않는다.
func (m *Manager) check(ctx context.Context) error {
	res, err := m.Runner.Run(ctx, platform.Command{Name: "sshd", Args: []string{"-t"}, Timeout: 15 * time.Second, MaxOutput: 8 << 10})
	if err != nil {
		return nil
	}
	if res.ExitCode != 0 {
		msg := strings.TrimSpace(string(res.Stderr))
		if i := strings.IndexByte(msg, '\n'); i > 0 {
			msg = msg[:i]
		}
		return errors.New(msg)
	}
	return nil
}

func (m *Manager) checkUser(user string) error {
	if !admin.ValidUser(user) {
		return errf(CodeInvalidInput, "the user name is not valid")
	}
	if m.Users != nil {
		for _, u := range m.Users() {
			if u == user {
				return nil
			}
		}
		return errf(CodeNotFound, "there is no login account named %s", user)
	}
	return nil
}

// ListKeys 는 사용자의 공개 키 목록이다.
func (m *Manager) ListKeys(ctx context.Context, user string) ([]Key, error) {
	if err := m.checkUser(user); err != nil {
		return nil, err
	}
	data, err := m.Keys.ReadAuthorizedKeys(ctx, user)
	if err != nil {
		return nil, errf(CodeInternal, "reading the keys: %v", err)
	}
	keys := ParseKeys(data)
	if keys == nil {
		keys = []Key{}
	}
	return keys, nil
}

// AddKey 는 사용자에게 공개 키를 등록한다.
func (m *Manager) AddKey(ctx context.Context, user, line string) (Key, bool, error) {
	if err := m.checkUser(user); err != nil {
		return Key{}, false, err
	}
	data, err := m.Keys.ReadAuthorizedKeys(ctx, user)
	if err != nil {
		return Key{}, false, errf(CodeInternal, "reading the keys: %v", err)
	}
	out, k, added, aerr := AddKey(data, line)
	if aerr != nil {
		return Key{}, false, errf(CodeInvalidInput, "%v", aerr)
	}
	if added {
		if err := m.Keys.WriteAuthorizedKeys(ctx, user, out); err != nil {
			return k, false, errf(CodeInternal, "saving the keys: %v", err)
		}
	}
	return k, added, nil
}

// RemoveKey 는 지문으로 키를 지운다.
func (m *Manager) RemoveKey(ctx context.Context, user, fingerprint string) error {
	if err := m.checkUser(user); err != nil {
		return err
	}
	data, err := m.Keys.ReadAuthorizedKeys(ctx, user)
	if err != nil {
		return errf(CodeInternal, "reading the keys: %v", err)
	}
	out, removed := RemoveKey(data, fingerprint)
	if !removed {
		return errf(CodeNotFound, "that key is not registered")
	}
	if err := m.Keys.WriteAuthorizedKeys(ctx, user, out); err != nil {
		return errf(CodeInternal, "saving the keys: %v", err)
	}
	return nil
}

// HostKeys 는 서버 호스트 키의 지문이다. 처음 접속할 때 클라이언트가 보여 주는 값과 비교한다.
func (m *Manager) HostKeys(ctx context.Context) []Key {
	dir := m.HostKeyDir
	if dir == "" {
		dir = "/etc/ssh"
	}
	matches, _ := filepath.Glob(filepath.Join(dir, "ssh_host_*_key.pub"))
	sort.Strings(matches)
	var out []Key
	for _, p := range matches {
		data, err := os.ReadFile(p)
		if err != nil {
			continue
		}
		if k, err := ParseKeyLine(string(data)); err == nil {
			k.Comment = filepath.Base(p)
			out = append(out, k)
		}
	}
	return out
}

// RecentLogins 는 최근 접속 결과다(가장 새것이 먼저, 최대 limit 개).
func (m *Manager) RecentLogins(ctx context.Context, limit int) ([]LoginEvent, error) {
	if limit < 1 || limit > 200 {
		limit = 50
	}
	res, err := m.Runner.Run(ctx, platform.Command{
		Name: "journalctl", Args: []string{"-u", sshUnit, "-n", "1000", "-o", "short-iso", "--no-pager"},
		Timeout: 20 * time.Second, MaxOutput: 1 << 20,
	})
	if err != nil {
		return nil, errf(CodeInternal, "journalctl: %v", err)
	}
	if res.ExitCode != 0 {
		return nil, errf(CodeInternal, "journalctl exited %d", res.ExitCode)
	}
	ev := ParseAuthLog(string(res.Stdout), limit)
	if ev == nil {
		ev = []LoginEvent{}
	}
	return ev, nil
}
