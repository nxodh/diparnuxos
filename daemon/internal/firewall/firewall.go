// Package firewall은 Opereta의 nftables 규칙 파일을 만든다. 순수 함수이며 nft를 실행하지 않는다.
//
// 이 패키지는 table inet opereta 하나만 다룬다. flush ruleset을 쓰지 않으므로 다른 테이블은 건드리지 않는다.
// 같은 파일을 다시 적용해도 결과가 같도록 테이블을 먼저 선언하고, 지운 다음 다시 정의한다.
// 이 nft 관용 형태는 nft(8)의 파일 입력 방식이다.
package firewall

import (
	"fmt"
	"regexp"
	"strings"
)

// defaultSSHPort는 SSHOpen이고 SSHPort가 0일 때 쓰는 포트다.
const defaultSSHPort = 22

// Options는 방화벽 규칙을 정하는 옵션이다.
type Options struct {
	APIPort int  // llama-server 포트, 1-65535
	APIOpen bool // true이면 APIPort를 연다(LAN 공개를 켰을 때만)
	SSHOpen bool // true이면 SSHPort를 연다
	SSHPort int  // 0이면 22
	// MDNSOpen 이 true 이면 mDNS(UDP 5353)를 연다. 이름(<호스트>.local)으로 찾게 하려면 LAN 공개와 함께 켠다.
	MDNSOpen bool
	// Open 은 기능(WireGuard, 원격 데스크톱, 웹 관리)이 여는 포트다. 기능이 켜져 있을 때만 넘긴다.
	Open []Open
	// Rules 는 사용자가 만든 규칙이다. 사용 중인 규칙만 규칙 파일에 들어간다.
	Rules []Rule
	// Trusted 는 모든 들어오는 연결을 허용할 인터페이스다(VPN 인터페이스 wg0).
	Trusted []string
}

// Extras 는 설정 밖에서 오는 규칙 재료다: 켜진 기능이 여는 포트, 사용자 규칙, 신뢰할 인터페이스.
type Extras struct {
	Open    []Open
	Rules   []Rule
	Trusted []string
}

var ifaceRE = regexp.MustCompile(`^[a-z][a-z0-9_-]{0,14}$`)

// Ruleset은 nftables 규칙 파일 전체를 만든다. 잘못된 포트는 오류를 돌려준다.
func Ruleset(o Options) (string, error) {
	if err := checkPort("API port", o.APIPort); err != nil {
		return "", fmt.Errorf("firewall: ruleset: %w", err)
	}
	sshPort := o.SSHPort
	if o.SSHOpen && sshPort == 0 {
		sshPort = defaultSSHPort
	}
	if sshPort != 0 {
		if err := checkPort("SSH port", sshPort); err != nil {
			return "", fmt.Errorf("firewall: ruleset: %w", err)
		}
	}

	var b strings.Builder
	b.WriteString("# Opereta nftables rules. Generated by operetad; do not edit by hand.\n")
	b.WriteString("# Manages only table inet opereta. Other tables are not touched.\n")
	b.WriteString("table inet opereta\n")
	b.WriteString("delete table inet opereta\n")
	b.WriteString("table inet opereta {\n")

	b.WriteString("\tchain input {\n")
	b.WriteString("\t\ttype filter hook input priority filter; policy drop;\n")
	b.WriteString("\t\tiif lo accept\n")
	b.WriteString("\t\tct state established,related accept\n")
	b.WriteString("\t\tct state invalid drop\n")
	b.WriteString("\t\t# ICMP (IPv4) and ICMPv6 (IPv6), needed for neighbor discovery and path MTU.\n")
	b.WriteString("\t\tmeta l4proto { icmp, icmpv6 } accept\n")
	b.WriteString("\t\t# DHCPv4 and DHCPv6 replies to this client.\n")
	b.WriteString("\t\tudp dport 68 accept\n")
	b.WriteString("\t\tudp dport 546 accept\n")
	if o.APIOpen {
		b.WriteString("\t\t# llama-server API (LAN exposure enabled; API key required).\n")
		fmt.Fprintf(&b, "\t\ttcp dport %d accept\n", o.APIPort)
	}
	if o.SSHOpen {
		b.WriteString("\t\t# SSH.\n")
		fmt.Fprintf(&b, "\t\ttcp dport %d accept\n", sshPort)
	}
	for _, name := range o.Trusted {
		if !ifaceRE.MatchString(name) {
			return "", fmt.Errorf("firewall: ruleset: invalid interface name %q", name)
		}
		fmt.Fprintf(&b, "\t\t# Trusted interface %s (VPN peers).\n", name)
		fmt.Fprintf(&b, "\t\tiifname \"%s\" accept\n", name)
	}
	if o.MDNSOpen {
		b.WriteString("\t\t# mDNS (the <host name>.local name).\n")
		b.WriteString("\t\tudp dport 5353 accept\n")
	}
	for _, op := range o.Open {
		if err := op.Validate(); err != nil {
			return "", fmt.Errorf("firewall: ruleset: %w", err)
		}
		fmt.Fprintf(&b, "\t\t# %s.\n", sanitizeComment(op.Name))
		for _, line := range nftLines(op.Protocol, op.Port, op.PortEnd, op.Source) {
			b.WriteString("\t\t" + line + "\n")
		}
	}
	for _, r := range o.Rules {
		if !r.Enabled {
			continue
		}
		if err := r.Validate(); err != nil {
			return "", fmt.Errorf("firewall: ruleset: rule %q: %w", r.Name, err)
		}
		fmt.Fprintf(&b, "\t\t# Rule: %s.\n", sanitizeComment(r.Name))
		for _, line := range nftLines(r.Protocol, r.Port, r.PortEnd, r.Source) {
			b.WriteString("\t\t" + line + "\n")
		}
	}
	b.WriteString("\t}\n")

	b.WriteString("\tchain forward {\n")
	b.WriteString("\t\ttype filter hook forward priority filter; policy drop;\n")
	b.WriteString("\t}\n")

	b.WriteString("\tchain output {\n")
	b.WriteString("\t\ttype filter hook output priority filter; policy accept;\n")
	b.WriteString("\t}\n")

	b.WriteString("}\n")
	return b.String(), nil
}

// checkPort는 포트가 1-65535 범위인지 본다.
func checkPort(what string, port int) error {
	if port < 1 || port > 65535 {
		return fmt.Errorf("%s %d is out of range 1-65535", what, port)
	}
	return nil
}
